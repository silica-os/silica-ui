// Copies the Silica Symbols font from a silica-icons checkout into the package.
//
// Usage, from the package root:
//
//   dart run tool/sync_symbols.dart ~/silica/silica-icons
//
// Copies `fonts/SilicaSymbols-{Light,Regular,Semibold}.otf` to `fonts/`, the Flutter icon
// constants `fonts/flutter/silica_symbols.dart` to `lib/src/amalfi/foundation/silica_symbols.g.dart`
// (with `kSilicaSymbolsPackage` set to `silica_ui`) and writes the name to codepoint table
// `lib/src/amalfi/foundation/silica_symbol_names.g.dart` from `fonts/codepoints.json`.
// Running it twice changes nothing.

import 'dart:convert';
import 'dart:io';

void main(List<String> args) {
  if (args.length != 1) {
    stderr.writeln('usage: dart run tool/sync_symbols.dart <silica-icons dir>');
    exitCode = 64;
    return;
  }
  final icons = args.single;
  for (final weight in ['Light', 'Regular', 'Semibold']) {
    File(
      '$icons/fonts/SilicaSymbols-$weight.otf',
    ).copySync('fonts/SilicaSymbols-$weight.otf');
  }
  const foundation = 'lib/src/amalfi/foundation';
  final dart = File('$icons/fonts/flutter/silica_symbols.dart')
      .readAsStringSync()
      .replaceFirst(
        'const String? kSilicaSymbolsPackage = null;',
        "const String? kSilicaSymbolsPackage = 'silica_ui';",
      );
  File('$foundation/silica_symbols.g.dart').writeAsStringSync(dart);

  final names =
      (jsonDecode(File('$icons/fonts/codepoints.json').readAsStringSync())
          as Map<String, dynamic>);
  final o = StringBuffer()
    ..writeln(
      '// GENERATED by tool/sync_symbols.dart from silica-icons fonts/codepoints.json.',
    )
    ..writeln('// Do not edit.')
    ..writeln()
    ..writeln(
      '/// Silica Symbols names and their private-use codepoints (identical in every weight).',
    )
    ..writeln('const Map<String, int> silicaSymbolCodepoints = {');
  for (final MapEntry(:key, :value) in names.entries) {
    o.writeln("  '$key': 0x${(value as String).toLowerCase()},");
  }
  o.writeln('};');
  File('$foundation/silica_symbol_names.g.dart').writeAsStringSync('$o');
}
